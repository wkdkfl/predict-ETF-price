def clone(model_par, text):
    """model_par 의 문단·런 서식을 그대로 쓰고 텍스트만 바꾼 새 <w:p> 요소."""
    el = copy.deepcopy(model_par._element)
    for child in list(el):
        if child.tag != qn("w:pPr"):
            el.remove(child)
    if model_par.runs:
        r = copy.deepcopy(model_par.runs[0]._element)
        for c in list(r):
            if c.tag != qn("w:rPr"):
                r.remove(c)
    else:
        r = OxmlElement("w:r")
    t = OxmlElement("w:t")
    t.set(qn("xml:space"), "preserve")
    t.text = text
    r.append(t)
    el.append(r)
    return el


